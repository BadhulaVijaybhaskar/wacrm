#!/usr/bin/env python3
"""Mechanically derive wacrm_schema.sql from a pg_dump of a DB with
migrations 001-058 applied (schema public).  Usage: gen.py dump.sql out.sql"""
import re, sys
src, out = sys.argv[1], sys.argv[2]
s = open(src).read()

# 0. drop pg_dump 17.6+ \\restrict / \\unrestrict psql meta-commands
s = re.sub(r"^\\(un)?restrict [^\n]*\n", "", s, flags=re.M)
assert not re.search(r"^\\", s, re.M)
# 1. drop pg_dump preamble (SETs, CREATE SCHEMA public, COMMENT ON SCHEMA public)
cut = s.index("COMMENT ON SCHEMA public IS 'standard public schema';")
s = s[cut:].split("\n", 1)[1]
s = s.replace("SET default_tablespace = '';\n", "")
s = s.replace("SET default_table_access_method = heap;\n", "")
assert not re.search(r"^SET |set_config", s, re.M), "unexpected SET left"

# 2. remove handle_new_user (auth.users trigger function; replaced by ensure_chat_profile)
m = re.search(r"--\n-- Name: handle_new_user\(\); Type: FUNCTION;.*?\n\$\$;\n", s, re.S)
assert m; s = s[:m.start()] + s[m.end():]
assert "FUNCTION public.handle_new_user" not in s

# 3. owner FK RESTRICT -> CASCADE
old = "REFERENCES auth.users(id) ON DELETE RESTRICT;"
assert s.count(old) == 1
s = s.replace(old, "REFERENCES auth.users(id) ON DELETE CASCADE;")

# 3b. drop profiles_insert: users never INSERT profiles directly; the only
#     creation paths are SECURITY DEFINER (ensure_chat_profile, redeem_invitation)
#     -- otherwise a user could self-insert with any account_id/account_role (Voice T9)
m = re.search(r"--\n-- Name: profiles profiles_insert; Type: POLICY;[^\n]*\n--\n\nCREATE POLICY profiles_insert ON public\.profiles FOR INSERT [^\n]*\n\n\n", s)
assert m; s = s[:m.start()] + s[m.end():]
assert "profiles_insert" not in s

# 4. schema rename public -> wacrm (object names, type refs, function bodies)
s = s.replace("public.", "wacrm.")
s = s.replace("Schema: public;", "Schema: wacrm;")
s = s.replace("SET search_path TO 'public'", "SET search_path TO 'wacrm', 'extensions'")
assert not re.search(r"\bpublic\b", s), re.findall(r".*\bpublic\b.*", s)[:5]

# 5. pin search_path on every function lacking one
def fix(mo):
    blk = mo.group(0)
    if "SET search_path" in blk: return blk
    return re.sub(r"\n    AS \$", "\n    SET search_path TO 'wacrm', 'extensions'\n    AS $", blk, count=1)
s = re.sub(r"CREATE FUNCTION wacrm\.[^\n]*\n(?:    [^\n]*\n)*?    AS \$", fix, s)
nf = len(re.findall(r"^CREATE FUNCTION", s, re.M))
ns = len(re.findall(r"^CREATE FUNCTION[^\n]*\n(?:    [^\n]*\n)*?    SET search_path TO 'wacrm', 'extensions'\n", s, re.M))
assert nf == ns == 27, (nf, ns)

# 6. restore real pgvector types (harness migrations used a float4[] stand-in)
s = s.replace("    embedding real[],", "    embedding extensions.vector(1536),")
s = s.replace("p_query_embedding::float4[]", "p_query_embedding::extensions.vector(1536)")
s = s.replace("ai_knowledge_chunks USING btree (id);", "ai_knowledge_chunks USING hnsw (embedding extensions.vector_cosine_ops);")
assert "float4" not in s and "real[]" not in s

tables = [l.strip() for l in open("tables.txt") if l.strip()]
SERVICE = ["_bcast_bump(uuid, text, integer)", "recompute_broadcast_counts(uuid)",
  "bump_conversation_on_inbound(uuid, text)", "increment_flow_execution_count(uuid)",
  "increment_automation_execution_count(uuid)", "claim_ai_reply_slot(uuid, integer)",
  "record_webhook_failure(uuid, integer)",
  "create_broadcast_with_recipients(uuid, uuid, text, text, text, integer, uuid[], jsonb[])"]
USER = ["is_account_member(uuid, wacrm.account_role_enum)", "filter_contacts_by_tags(uuid[], text, integer, integer)",
  "match_ai_knowledge_fts(uuid, text, integer)", "match_ai_knowledge_semantic(uuid, text, integer)",
  "peek_invitation(text)", "redeem_invitation(text)", "remove_account_member(uuid)",
  "set_member_role(uuid, wacrm.account_role_enum)", "transfer_account_ownership(uuid)",
  "touch_presence(text)", "ensure_chat_profile(text)"]

ENSURE = open("ensure_chat_profile.sql").read()

head = """-- Astra Chat shared-project schema (wacrm)
-- GENERATED by gen.py from a pg_dump --schema-only --schema=public of a
-- scratch database with supabase/migrations 001-058 applied in order.
-- Do not hand-edit; regenerate.  Documented deviations from the 058 end
-- state: see VERIFY.md "Exceptions".
-- Installs atomically; refuses to run if schema wacrm already exists.
BEGIN;
SET LOCAL search_path = wacrm, extensions;
SET LOCAL check_function_bodies = false;
SET LOCAL client_min_messages = warning;

DO $guard$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_namespace WHERE nspname = 'wacrm') THEN
    RAISE EXCEPTION 'schema wacrm already exists; run rollback_wacrm.sql first (nothing was changed)';
  END IF;
  IF to_regprocedure('extensions.uuid_generate_v4()') IS NULL THEN
    RAISE EXCEPTION 'uuid-ossp must be installed in schema extensions (see live-precheck.sql)';
  END IF;
  IF EXISTS (SELECT 1 FROM pg_extension e JOIN pg_namespace n ON n.oid = e.extnamespace
             WHERE e.extname = 'vector' AND n.nspname <> 'extensions') THEN
    RAISE EXCEPTION 'pgvector is installed outside schema extensions; aborting';
  END IF;
END
$guard$;

-- SHARED CHANGE (outside wacrm): wacrm.ai_knowledge_chunks.embedding is
-- vector(1536) with an hnsw index, and match_ai_knowledge_semantic uses <=>.
-- Not dropped by rollback_wacrm.sql (other products may start using it).
CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA extensions;  -- @@VECTOR_EXT@@

CREATE SCHEMA wacrm;
"""
g = ["", "--", "-- Privileges: explicit, per object. Nothing for anon or PUBLIC.", "--",
     "REVOKE ALL ON SCHEMA wacrm FROM PUBLIC, anon;",
     "GRANT USAGE ON SCHEMA wacrm TO authenticated, service_role;",
     "REVOKE ALL ON ALL TABLES IN SCHEMA wacrm FROM PUBLIC, anon, authenticated, service_role;",
     "REVOKE ALL ON ALL FUNCTIONS IN SCHEMA wacrm FROM PUBLIC, anon, authenticated, service_role;", ""]
for t in tables:
    if t == "notifications":
        g.append("GRANT SELECT, INSERT, DELETE ON TABLE wacrm.notifications TO authenticated;")
        g.append("GRANT UPDATE (read_at) ON TABLE wacrm.notifications TO authenticated;")
    elif t == "profiles":
        g.append("-- profiles: no INSERT for users (created only via SECURITY DEFINER ensure_chat_profile / redeem_invitation)")
        g.append("GRANT SELECT, UPDATE, DELETE ON TABLE wacrm.profiles TO authenticated;")
    else:
        g.append(f"GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE wacrm.{t} TO authenticated;")
    g.append(f"GRANT ALL ON TABLE wacrm.{t} TO service_role;")
g += ["", "-- service-only RPCs / helpers (called with the service client or from SECURITY DEFINER code)"]
g += [f"GRANT EXECUTE ON FUNCTION wacrm.{f} TO service_role;" for f in SERVICE]
g += ["", "-- user-facing RPCs (and is_account_member, which RLS policies call as the user)"]
g += [f"GRANT EXECUTE ON FUNCTION wacrm.{f} TO authenticated, service_role;" for f in USER]
g += ["", "-- trigger functions, _bcast_cols_for_status and merge_duplicate_*: no EXECUTE grants",
      "-- (triggers do not check EXECUTE; the merge functions are one-off maintenance).", "",
      "COMMIT;", ""]
open(out, "w").write(head + s.rstrip() + "\n\n" + ENSURE.strip() + "\n" + "\n".join(g))
print("ok", nf + 1, "functions,", len(tables), "tables")
